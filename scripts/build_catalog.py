#!/usr/bin/env python3
"""Generate docs/CATALOG.md and docs/catalog.json from tweaks/*/*/tweak.json.

Usage:
  python scripts/build_catalog.py           # write files
  python scripts/build_catalog.py --check   # exit 1 if files are out of date (CI)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load() -> list[dict]:
    items = []
    for f in sorted((ROOT / "tweaks").glob("*/*/tweak.json")):
        meta = json.loads(f.read_text(encoding="utf-8"))
        meta["path"] = f.parent.relative_to(ROOT).as_posix()
        items.append(meta)
    return sorted(items, key=lambda m: (m["category"], m["name"].lower()))


def render_md(items: list[dict]) -> str:
    out = ["# Tweak Catalog", "",
           "_Generated by `scripts/build_catalog.py`. Do not edit by hand._", "",
           f"**{len(items)} tweaks.**", ""]
    cat = None
    for m in items:
        if m["category"] != cat:
            if cat is not None:
                out.append("")
            cat = m["category"]
            out += [f"## {cat}", "", "| Tweak | Description | Admin | Windows | Tested |",
                    "|---|---|---|---|---|"]
        admin = "Yes" if m["requiresAdmin"] else "No"
        tested = "Yes" if m["tested"] else "Not yet"
        out.append(f"| [{m['name']}](../{m['path']}/README.md) | {m['description']} | "
                   f"{admin} | {m['windows']} | {tested} |")
    return "\n".join(out) + "\n"


def main() -> int:
    items = load()
    md = render_md(items)
    js = json.dumps(items, indent=2) + "\n"
    targets = {ROOT / "docs" / "CATALOG.md": md, ROOT / "docs" / "catalog.json": js}
    if "--check" in sys.argv:
        stale = [p.name for p, c in targets.items()
                 if not p.exists() or p.read_text(encoding="utf-8") != c]
        if stale:
            print(f"Out of date: {', '.join(stale)}. Run: python scripts/build_catalog.py")
            return 1
        print("Catalog is up to date.")
        return 0
    for p, c in targets.items():
        p.write_text(c, encoding="utf-8", newline="\n")
    print(f"Wrote catalog for {len(items)} tweaks.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
